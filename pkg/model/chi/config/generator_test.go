// TestGetRemoteServersClusterSecret walks the secret-source matrix that drives
// the <secret> element in autogenerated remote_servers.xml clusters.
//
// The helper is a method on *Generator but doesn't dereference the receiver,
// so we invoke it on a nil receiver — keeps the test free of Generator's
// CR / namer / options construction overhead.
func TestGetRemoteServersClusterSecret(t *testing.T) {
	cases := []struct {
		name   string
		secret *chi.ClusterSecret
		want   string
	}{
		{
			name:   "nil secret renders nothing",
			secret: nil,
			want:   "",
		},
		{
			name:   "empty struct (Unspecified source) renders nothing",
			secret: &chi.ClusterSecret{},
			want:   "",
		},
		{
			name:   "plaintext renders inline value",
			secret: &chi.ClusterSecret{Value: "topsecret"},
			want:   "<secret>topsecret</secret>\n",
		},
		{
			name:   "plaintext XML-escapes ampersand",
			secret: &chi.ClusterSecret{Value: "a&b"},
			want:   "<secret>a&amp;b</secret>\n",
		},
		{
			name:   "plaintext XML-escapes angle brackets",
			secret: &chi.ClusterSecret{Value: "<tag>"},
			want:   "<secret>&lt;tag&gt;</secret>\n",
		},
		{
			name:   "plaintext XML-escapes CDATA terminator",
			secret: &chi.ClusterSecret{Value: "x]]>y"},
			// encoding/xml.EscapeText escapes ']]>' to ']]&gt;' to prevent
			// breaking out of a CDATA section that a future renderer might
			// wrap the value in.
			want: "<secret>x]]&gt;y</secret>\n",
		},
		{
			name:   "valueFrom (secret_ref) renders env-var reference",
			secret: &chi.ClusterSecret{ValueFrom: &types.DataSource{SecretKeyRef: &core.SecretKeySelector{}}},
			want:   `<secret from_env="CLICKHOUSE_INTERNODE_CLUSTER_SECRET" />` + "\n",
		},
		{
			name:   "auto renders env-var reference",
			secret: &chi.ClusterSecret{Auto: types.NewStringBool(true)},
			want:   `<secret from_env="CLICKHOUSE_INTERNODE_CLUSTER_SECRET" />` + "\n",
		},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			var b bytes.Buffer
			// Nil receiver — helper doesn't touch *Generator.
			var g *Generator
			g.getRemoteServersClusterSecret(c.secret, 0, &b)
			got := b.String()
			if got != c.want {
				t.Fatalf("output mismatch:\nwant: %q\ngot:  %q", c.want, got)
			}
		})
	}
}

// TestGetRemoteServersClusterSecret_IndentLevel sanity-checks that the indent
// parameter is honoured — caller passes indent+4 at every site, and a
// regression that hardcoded indent would silently misalign the rendered XML.
func TestGetRemoteServersClusterSecret_IndentLevel(t *testing.T) {
	secret := &chi.ClusterSecret{Value: "v"}
	for _, indent := range []int{0, 4, 8, 16} {
		var b bytes.Buffer
		var g *Generator
		g.getRemoteServersClusterSecret(secret, indent, &b)
		out := b.String()
		// util.Iline pads with `indent` spaces before the content.
		wantPrefix := strings.Repeat(" ", indent) + "<secret>"
		if !strings.HasPrefix(out, wantPrefix) {
			t.Fatalf("indent=%d: expected prefix %q, got %q", indent, wantPrefix, out)
		}
	}
}

// newLowPriorityTestCR builds a minimal CR with one cluster of one shard and
// two replicas, and returns the CR together with both of its hosts. The hosts
// carry a port because the normalizer does not run here, and a rendered
// <port>0</port> would be confusing in a failure dump.
func newLowPriorityTestCR() (cr *chi.ClickHouseInstallation, first, second *chi.Host) {
	first = &chi.Host{Name: "0", TCPPort: types.NewInt32(9000)}
	second = &chi.Host{Name: "1", TCPPort: types.NewInt32(9000)}

	cr = &chi.ClickHouseInstallation{}
	cr.Name = "test"
	cr.Namespace = "test"
	cr.Spec.Defaults = chi.NewDefaults()
	cr.Spec.Configuration = &chi.Configuration{
		Clusters: []*chi.Cluster{
			{
				Name: "cluster",
				Layout: &chi.ChiClusterLayout{
					Shards: []*chi.ChiShard{
						{Name: "0", Hosts: []*chi.Host{first, second}},
					},
					Replicas: []*chi.ChiReplica{
						{Name: "0", Hosts: []*chi.Host{first}},
						{Name: "1", Hosts: []*chi.Host{second}},
					},
				},
			},
		},
	}
	// Wires host addresses and the back-pointers to the CR, as the normalizer does.
	cr.Fill()

	return cr, first, second
}

// remoteServersReplica is one <replica> block of rendered remote_servers.
type remoteServersReplica struct {
	host        string
	lowPriority bool
}

// parseRemoteServersReplicas splits rendered remote_servers into its <replica>
// blocks. A host appears once per cluster it belongs to, including the
// autogenerated ones, so blocks are returned as a list rather than a map.
func parseRemoteServersReplicas(t *testing.T, remoteServers string) (replicas []remoteServersReplica) {
	t.Helper()
	for _, block := range strings.Split(remoteServers, "<replica>")[1:] {
		block, _, found := strings.Cut(block, "</replica>")
		if !found {
			t.Fatalf("unterminated <replica> block in:\n%s", remoteServers)
		}
		_, host, found := strings.Cut(block, "<host>")
		if !found {
			t.Fatalf("<replica> block without a <host> in:\n%s", remoteServers)
		}
		host, _, _ = strings.Cut(host, "</host>")
		replicas = append(replicas, remoteServersReplica{
			host:        host,
			lowPriority: strings.Contains(block, "<priority>1000</priority>"),
		})
	}
	return replicas
}

// TestGetRemoteServersLowPriority covers the de-prioritisation that
// descendHostInClickHouseCluster performs before a host is restarted: the host
// it marks must come out of remote_servers with <priority>1000</priority>, so
// that peers prefer its replicas while it goes down, and must come back to
// normal priority once the mark is removed.
//
// Peers only learn about it through the common ConfigMap, so rendering the
// unmarked and the marked host identically is a silent failure: the ConfigMap
// does not change, no Pod remounts it, and no peer reloads.
func TestGetRemoteServersLowPriority(t *testing.T) {
	cr, descended, peer := newLowPriorityTestCR()
	generator := NewGenerator(cr, namer.New(), &GeneratorOptions{})
	descendedHost := generator.getRemoteServersReplicaHostname(descended)
	peerHost := generator.getRemoteServersReplicaHostname(peer)

	atNormalPriority := generator.getRemoteServers(nil)
	if strings.Contains(atNormalPriority, "<priority>") {
		t.Fatalf("no host is marked low priority, but remote_servers carries a priority:\n%s", atNormalPriority)
	}

	descended.GetReconcileAttributes().SetLowPriority()
	descendedOut := generator.getRemoteServers(nil)
	if descendedOut == atNormalPriority {
		t.Fatalf("remote_servers is unchanged after %s was marked low priority, so the ConfigMap never changes and peers never reload:\n%s",
			descendedHost, descendedOut)
	}

	marked := 0
	for _, replica := range parseRemoteServersReplicas(t, descendedOut) {
		switch replica.host {
		case descendedHost:
			if !replica.lowPriority {
				t.Errorf("replica %s is missing <priority>1000</priority> in:\n%s", replica.host, descendedOut)
			}
			marked++
		case peerHost:
			if replica.lowPriority {
				t.Errorf("replica %s is not the descended host but carries <priority>1000</priority> in:\n%s", replica.host, descendedOut)
			}
		default:
			t.Errorf("unexpected replica %s in:\n%s", replica.host, descendedOut)
		}
	}
	if marked == 0 {
		t.Fatalf("descended host %s is not present in remote_servers at all:\n%s", descendedHost, descendedOut)
	}

	descended.GetReconcileAttributes().UnsetLowPriority()
	if restored := generator.getRemoteServers(nil); restored != atNormalPriority {
		t.Errorf("unsetting low priority did not restore remote_servers.\nexpected:\n%s\ngot:\n%s", atNormalPriority, restored)
	}
}
